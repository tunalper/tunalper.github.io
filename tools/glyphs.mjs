// ------------------------------------------------------------------- encode
const encSmall = {};
for (const [ch, rows] of Object.entries(G)) {
  const r8 = [];
  for (let y = 0; y < 8; y++) {
    const s = (rows[y] || '').padEnd(6, '.');
    let v = 0;
    for (let x = 0; x < 6; x++) if (s[x] === '#') v |= 1 << (5 - x);
    r8.push(v);
  }
  encSmall[ch] = r8;
}
const encDisplay = {};
for (const [ch, rows] of Object.entries(D)) {
  const w = rows[0].length;
  for (const r of rows) if (r.length !== w) throw new Error('display width mismatch ' + ch);
  encDisplay[ch] = { w, rows: rows.map((r) => parseInt(r.replace(/#/g, '1').replace(/\./g, '0'), 2)) };
}

