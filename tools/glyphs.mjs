// "broken" half-letters: top of one capital fused to the bottom of another,
// then bitten by a seeded rng. They read like letters you almost recognise.
let seed = 0x5c711a;
const rnd = () => ((seed = (seed * 1103515245 + 12345) >>> 0) / 4294967296);
const caps = 'ABCDEFGHJKLMNOPRSTUVWXYZ'.split('');
const BROKEN = [];
for (let i = 0; i < 48; i++) {
  const a = G[caps[(rnd() * caps.length) | 0]];
  const b = G[caps[(rnd() * caps.length) | 0]];
  const cut = 2 + ((rnd() * 4) | 0);
  const rows = [];
  for (let y = 0; y < 7; y++) rows.push((y < cut ? a[y] : b[y]).split(''));
  // erase a fragment so it never resolves into a real letter
  const mode = (rnd() * 4) | 0;
  if (mode === 0) { const c = (rnd() * 5) | 0; for (let y = 0; y < 7; y++) if (rnd() < 0.7) rows[y][c] = '.'; }
  if (mode === 1) { const r = (rnd() * 7) | 0; rows[r] = rows[r].map(() => '.'); }
  if (mode === 2) { for (let k = 0; k < 3; k++) { const x = (rnd() * 5) | 0, y = (rnd() * 7) | 0; rows[y][x] = rows[y][x] === '#' ? '.' : '#'; } }
  if (mode === 3) { const off = rnd() < 0.5 ? 1 : -1; const r0 = cut; for (let y = r0; y < 7; y++) { const s = rows[y].join(''); rows[y] = (off > 0 ? '.' + s.slice(0, 4) : s.slice(1) + '.').split(''); } }
  const cp = 0xE010 + i;
  icon(cp, rows.map((r) => r.join('')));
  BROKEN.push(cp);
}

