// full-cell glyphs (6 wide, 8 tall) - redaction bars must join seamlessly
const cell = (fn) => {
  const rows = [];
  for (let y = 0; y < 8; y++) {
    let r = '';
    for (let x = 0; x < 6; x++) r += fn(x, y) ? '#' : '.';
    rows.push(r);
  }
  return rows;
};
def('█', cell(() => true));
def('▓', cell((x, y) => !((x % 2 === 1) && (y % 2 === 1))));
def('▒', cell((x, y) => (x + y) % 2 === 0));
def('░', cell((x, y) => (x % 2 === 0) && (y % 2 === 0)));
def('▀', cell((x, y) => y < 4));
def('▄', cell((x, y) => y >= 4));
def('▌', cell((x) => x < 3));
def('▐', cell((x) => x >= 3));
def('─', cell((x, y) => y === 3));
def('│', cell((x) => x === 2));
def('┼', cell((x, y) => x === 2 || y === 3));

